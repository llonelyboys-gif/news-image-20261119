const BLANK: number[] = [0, 0, 0, 0, 0, 0, 0];

/** Pixel width of one character cell (glyph + 1 column gap) at a scale. */
export function charW(scale: number): number {
  return 6 * scale;
}

/** Pixel height of one text line at a scale. */
export function lineH(scale: number): number {
  return 7 * scale;
}

/** Pixel width of a string at a scale. */
export function textW(text: string, scale: number): number {
  return text.length * charW(scale) - scale; // no trailing gap
}

export function drawText(cv: Canvas, text: string, x: number, y: number, scale: number, c: RGB): void {
  const upper = text.toUpperCase();
  for (let i = 0; i < upper.length; i += 1) {
    const glyph = GLYPHS[upper[i]] ?? BLANK;
    const ox = x + i * charW(scale);
    for (let row = 0; row < 7; row += 1) {
      const bits = glyph[row];
      for (let col = 0; col < 5; col += 1) {
        if (bits & (1 << (4 - col))) cv.rect(ox + col * scale, y + row * scale, scale, scale, c);
      }
    }
  }
}

/** Split text into lines that fit maxWidth, breaking on spaces. */
export function wrapText(text: string, maxWidth: number, scale: number): string[] {
  const words = text.split(' ');
  const lines: string[] = [];
  let cur = '';
  for (const word of words) {
    const trial = cur === '' ? word : `${cur} ${word}`;
    if (textW(trial, scale) <= maxWidth) {
      cur = trial;
    } else {
      if (cur !== '') lines.push(cur);
      // A single word wider than the line: hard-split it.
      let rest = word;
      while (textW(rest, scale) > maxWidth) {
        const fit = Math.max(1, Math.floor(maxWidth / charW(scale)));
        lines.push(rest.slice(0, fit));
        rest = rest.slice(fit);
      }
      cur = rest;
    }
  }
  if (cur !== '') lines.push(cur);
  return lines;
}

/** Draw wrapped text; returns the y just below the last line. */
export function drawParagraph(
  cv: Canvas,
  text: string,
  x: number,
  y: number,
  maxWidth: number,
  scale: number,
  c: RGB,
  leading?: number,
): number {
  const lines = wrapText(text, maxWidth, scale);
  const lh = lineH(scale) + (leading ?? Math.max(2, Math.floor(scale * 0.8)));
  for (let i = 0; i < lines.length; i += 1) drawText(cv, lines[i], x, y + i * lh, scale, c);
  return y + lines.length * lh;
}
